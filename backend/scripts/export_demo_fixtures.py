"""
Export Deterministic Demo Scenarios to Frontend Fixture.

Serializes the exact backend demo scenarios generated by
`evaluation.demo_scenarios.get_demo_scenarios()` to
`frontend/src/data/demoScenariosFixture.json`.

This allows the frontend to run in a 100% offline, network-independent
evaluation mode without needing the backend or external services running.
"""

import json
from pathlib import Path
import sys

# Ensure backend root is on sys.path
backend_dir = Path(__file__).resolve().parent.parent
if str(backend_dir) not in sys.path:
    sys.path.insert(0, str(backend_dir))

from app.schemas.investigation import (
    DemoScenarioListResponse,
    DemoScenarioResponse,
)
from evaluation.demo_scenarios import get_demo_scenarios


def export_fixtures() -> Path:
    demos = get_demo_scenarios()
    scenarios = [
        DemoScenarioResponse(
            scenario_name=d.scenario_name,
            scenario_title=d.scenario_title,
            semantic_expectation=d.semantic_expectation,
            merchant_name=d.merchant_name,
            anomaly_summary=d.anomaly_summary,
            evidence_count=d.evidence_count,
            eci_score=d.eci_score,
            eci_band=d.eci_band,
            factors_summary=d.factors_summary,
            contradictions=d.contradictions,
            analyst_checklist=d.analyst_checklist,
            dossier=d.dossier,
            evidence_items=d.evidence_items,
            verification_items=d.verification_items,
        )
        for d in demos
    ]
    response = DemoScenarioListResponse(scenarios=scenarios)

    # Destination in frontend
    frontend_data_dir = backend_dir.parent / "frontend" / "src" / "data"
    frontend_data_dir.mkdir(parents=True, exist_ok=True)
    target_path = frontend_data_dir / "demoScenariosFixture.json"

    data = response.model_dump(mode="json")
    with open(target_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)

    print(f"Successfully exported {len(scenarios)} demo scenarios to {target_path}")
    return target_path


if __name__ == "__main__":
    export_fixtures()
